/**
 * Cookie parsing and serialisation without a dependency.
 *
 * Fastify does not parse cookies unless a plugin is registered, and the only cookies this service
 * consumes are its own two (`seamnex_session`, `seamnex_csrf`). Parsing them locally keeps the supply-chain
 * surface unchanged and lets the parser be strict: a malformed pair is ignored rather than coerced,
 * and no value is ever logged.
 */

export type SameSite = 'Lax' | 'Strict' | 'None';

export type CookieOptions = {
  readonly path?: string;
  readonly maxAgeSeconds?: number;
  readonly httpOnly?: boolean;
  readonly secure?: boolean;
  readonly sameSite?: SameSite;
  readonly domain?: string;
  readonly expires?: Date;
};

/** Cookie names are tokens; anything else could inject a header. */
const COOKIE_NAME = /^[!#$%&'*+\-.^_`|~0-9A-Za-z]+$/;

export function parseCookies(header: string | undefined): Record<string, string> {
  const cookies: Record<string, string> = {};
  if (header === undefined || header.length === 0 || header.length > 8_192) return cookies;

  for (const pair of header.split(';')) {
    const index = pair.indexOf('=');
    if (index <= 0) continue;
    const name = pair.slice(0, index).trim();
    const value = pair.slice(index + 1).trim();
    if (!COOKIE_NAME.test(name) || cookies[name] !== undefined) continue;
    try {
      cookies[name] = decodeURIComponent(value);
    } catch {
      // A percent-encoded value we cannot decode is not ours; skip it instead of failing the request.
    }
  }
  return cookies;
}

export function serializeCookie(name: string, value: string, options: CookieOptions = {}): string {
  if (!COOKIE_NAME.test(name)) throw new Error(`Invalid cookie name: ${name}`);
  // Values are generated by this service (base64url or hex); rejecting separators is defence in
  // depth against a future caller passing user input here.
  if (/[\r\n;,]/.test(value)) throw new Error('Cookie value contains a reserved character');

  const parts = [`${name}=${encodeURIComponent(value)}`];
  parts.push(`Path=${options.path ?? '/'}`);
  if (options.maxAgeSeconds !== undefined)
    parts.push(`Max-Age=${Math.max(0, Math.floor(options.maxAgeSeconds))}`);
  if (options.expires !== undefined) parts.push(`Expires=${options.expires.toUTCString()}`);
  if (options.domain !== undefined) parts.push(`Domain=${options.domain}`);
  if (options.httpOnly === true) parts.push('HttpOnly');
  if (options.secure === true) parts.push('Secure');
  parts.push(`SameSite=${options.sameSite ?? 'Lax'}`);
  return parts.join('; ');
}

export function clearCookie(name: string, options: CookieOptions = {}): string {
  return serializeCookie(name, '', { ...options, maxAgeSeconds: 0, expires: new Date(0) });
}

/** The four cookie attributes the session surface owns. Kept narrow so a caller cannot forget one. */
export type SessionCookieConfig = {
  readonly SESSION_COOKIE_NAME: string;
  readonly CSRF_COOKIE_NAME: string;
  readonly SESSION_COOKIE_SECURE: boolean;
  readonly SESSION_COOKIE_DOMAIN?: string | undefined;
};

/**
 * The pair that constitutes a signed-in browser (ADR-BE-10, ADR-BE-13).
 *
 * - `seamnex_session` is `HttpOnly`, so no script — ours or an injected one — can read the credential.
 * - `seamnex_csrf` is readable **on purpose**: the SPA echoes it in `x-seamnex-csrf`. It is not a credential
 *   on its own; the server compares it with the token stored in the session record.
 * - `Max-Age` is the *remaining* idle lifetime, so an active user's cookie is renewed on every
 *   response instead of dying at the original sign-in deadline (ADR-BE-13).
 */
export function sessionCookieHeaders(
  config: SessionCookieConfig,
  input: { sid: string; csrfToken: string; maxAgeSeconds: number },
): string[] {
  const secure = config.SESSION_COOKIE_SECURE;
  // The domain has to be on the cookie or forward-auth routes are unreachable: the edge asks for a
  // session the browser only holds for the portal's own host. Absent keeps it host-only.
  const scope =
    config.SESSION_COOKIE_DOMAIN === undefined ? {} : { domain: config.SESSION_COOKIE_DOMAIN };
  const maxAgeSeconds = Math.max(1, Math.floor(input.maxAgeSeconds));
  return [
    serializeCookie(config.SESSION_COOKIE_NAME, input.sid, {
      httpOnly: true,
      secure,
      sameSite: 'Lax',
      maxAgeSeconds,
      ...scope,
    }),
    serializeCookie(config.CSRF_COOKIE_NAME, input.csrfToken, {
      httpOnly: false,
      secure,
      sameSite: 'Lax',
      maxAgeSeconds,
      ...scope,
    }),
  ];
}

/** Both cookies, cleared with the same attributes they were set with. */
export function clearSessionCookieHeaders(config: SessionCookieConfig): string[] {
  const secure = config.SESSION_COOKIE_SECURE;
  const scope =
    config.SESSION_COOKIE_DOMAIN === undefined ? {} : { domain: config.SESSION_COOKIE_DOMAIN };
  return [
    clearCookie(config.SESSION_COOKIE_NAME, { httpOnly: true, secure, sameSite: 'Lax', ...scope }),
    clearCookie(config.CSRF_COOKIE_NAME, { httpOnly: false, secure, sameSite: 'Lax', ...scope }),
  ];
}

/** Reads one header value as a single string, tolerating Fastify's `string[]` union. */
export function headerValue(
  headers: Readonly<Record<string, string | string[] | undefined>>,
  name: string,
): string | undefined {
  const value = headers[name];
  const single = Array.isArray(value) ? value[0] : value;
  if (typeof single !== 'string') return undefined;
  const trimmed = single.trim();
  return trimmed.length > 0 ? trimmed : undefined;
}
